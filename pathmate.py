# Regex that splits at sentence boundaries (., !, ?) followed by a space or end
_SENTENCE_END = re.compile(r'(?<=[.!?])\s+')


class PersonalAI:
    def __init__(self):
        self.client = genai.Client(api_key=API_KEY)

    # ── STREAMING query (the magic) ──────────────────────
    def process_query_streaming(self, frame, question: str):
        """
        Sends image + question to Gemini using STREAMING.
        Yields complete sentences as they arrive from the model,
        so TTS can start speaking immediately.

        Retries transient failures (e.g. the known intermittent 404 on the
        gemini-3.5-flash alias) as long as nothing has been yielded yet,
        so a hiccup doesn't just go silent.
        """
        # Downscale to 640×480 — plenty for Gemini, uploads 4× faster
        frame_small = cv2.resize(frame, (640, 480))
        rgb = cv2.cvtColor(frame_small, cv2.COLOR_BGR2RGB)
        pil_image = Image.fromarray(rgb)

        for attempt in range(MAX_RETRIES + 1):
            got_any = False
            buffer = ""
            try:
                stream = self.client.models.generate_content_stream(
                    model=MODEL,
                    contents=[pil_image, question],
                    config=types.GenerateContentConfig(
                        system_instruction=SYSTEM_PROMPT,
                        # Low thinking effort = the model starts talking
                        # almost immediately instead of reasoning first.
                        # Try "minimal" if you want it even faster and can
                        # accept slightly shallower reasoning.
                        thinking_config=types.ThinkingConfig(
                            thinking_level="low"
                        ),
                    ),
                )

                for chunk in stream:
                    if chunk.text:
                        got_any = True
                        buffer += chunk.text

                        # Yield every complete sentence as soon as it arrives
                        parts = _SENTENCE_END.split(buffer)
                        if len(parts) > 1:
                            for sentence in parts[:-1]:
                                sentence = sentence.strip()
                                if sentence:
                                    yield sentence
                            buffer = parts[-1]  # keep the incomplete tail

                if buffer.strip():
                    yield buffer.strip()
                return  # success — done

            except Exception as e:
                print(f"[Gemini Error] attempt {attempt + 1}: {e}")
                if got_any:
                    # We already spoke part of an answer — don't retry and
                    # risk repeating/duplicating speech. Just stop here.
                    return
                if attempt < MAX_RETRIES:
                    time.sleep(0.6)
                    continue
                yield "Sorry, I had trouble reaching the assistant. Please try again."
                return

    # ── Non-streaming fallback ───────────────────────────
    def process_query(self, frame, question: str) -> str:
        return " ".join(self.process_query_streaming(frame, question))


# ─────────────────────────────────────────────
# SHARED STATE
# ─────────────────────────────────────────────
_latest_frame = None
_frame_lock = threading.Lock()
_processing = threading.Event()        # set while a query is in-flight


# ─────────────────────────────────────────────
# MIC LISTENER
# ─────────────────────────────────────────────
def _listen_loop(ai: PersonalAI):
    rec = sr.Recognizer()
    rec.pause_threshold = 0.5          # react faster to silence
    rec.dynamic_energy_threshold = True
    rec.energy_threshold = 300         # sensible starting point

    try:
        mic = sr.Microphone()
    except Exception as e:
        print(f"[Mic Error] {e}")
        speak("Microphone not found.")
        return

    # Quick calibration — done once, up front.
    try:
        with mic as src:
            print("[Mic] Calibrating...")
            rec.adjust_for_ambient_noise(src, duration=0.5)
    except Exception as e:
        print(f"[Mic Error] {e}")
        speak("Microphone not found.")
        return

    speak(f"Personal Assistant ready. Say {WAKE_WORD.title()} followed by your question.")

    def _on_audio(recognizer, audio):
        # Ignore audio captured while we're mid-query or mid-speech, so we
        # don't process a stacked request or accidentally transcribe our
        # own TTS output picked up by the mic.
        if _processing.is_set() or _is_speaking.is_set():
            return

        try:
            command = recognizer.recognize_google(audio).lower()
        except sr.UnknownValueError:
            return  # nothing recognisable
        except sr.RequestError as e:
            print(f"[STT API Error]: {e}")
            return

        print(f"[Heard]: {command}")

        if WAKE_WORD not in command:
            return

        parts = command.split(WAKE_WORD, 1)
        question = parts[1].strip() if len(parts) > 1 and parts[1].strip() else ""
        if not question:
            question = "What do you see in front of me?"

        print(f"[Query]: {question}")

        with _frame_lock:
            frame = _latest_frame.copy() if _latest_frame is not None else None

        if frame is None:
            speak("Camera not ready yet.")
            return

        _processing.set()

        def _stream_and_speak(frm, q):
            try:
                for sentence in ai.process_query_streaming(frm, q):
                    safe = sentence.encode("ascii", "ignore").decode("ascii")
                    print(f"[AI]: {safe}")
                    speak(sentence)
            except Exception as e:
                print(f"[Stream Error] {e}")
                speak("Sorry, something went wrong.")
            finally:
                _processing.clear()

        threading.Thread(
            target=_stream_and_speak,
            args=(frame, question),
            daemon=True,
        ).start()

    # Keeps the microphone stream open continuously in its own background
    # thread and calls _on_audio for each detected phrase — no more
    # opening/closing the mic on every polling cycle, no more gaps.
    stop_listening = rec.listen_in_background(mic, _on_audio, phrase_time_limit=5)

    try:
        while not _speech_stop.is_set():
            time.sleep(0.2)
    finally:
        stop_listening(wait_for_stop=False)


# ─────────────────────────────────────────────
# MAIN — camera loop + listener thread
# ─────────────────────────────────────────────
def main():
    global _latest_frame

    print("=" * 55)
    print("  PathMate — Personal AI Assistant (Streaming)")
    print("=" * 55)
    print("Controls:")
    print("  Q  ->  Quit")
    print(f"  Say '{WAKE_WORD.title()}, [question]' to ask.")
    print("=" * 55)

    ai = PersonalAI()

    cap = cv2.VideoCapture(CAMERA_INDEX)
    cap.set(cv2.CAP_PROP_FRAME_WIDTH, 1280)
    cap.set(cv2.CAP_PROP_FRAME_HEIGHT, 720)

    if not cap.isOpened():
        print("ERROR: Cannot open camera.")
        return

    # Start mic listener
    threading.Thread(target=_listen_loop, args=(ai,), daemon=True).start()

    try:
        while True:
            ret, frame = cap.read()
            if not ret:
                print("Camera read failed.")
                break

            # Update the shared frame for the mic thread to grab
            with _frame_lock:
                _latest_frame = frame

            # ── On-screen status ──
            if _processing.is_set():
                color, label = (0, 165, 255), "Processing..."
            elif _is_speaking.is_set():
                color, label = (255, 200, 0), "Speaking..."
            else:
                color, label = (0, 255, 0), f"Listening for '{WAKE_WORD}'"

            cv2.putText(
                frame, label, (10, frame.shape[0] - 20),
                cv2.FONT_HERSHEY_SIMPLEX, 0.7, color, 2,
            )

            cv2.imshow("PathMate AI Assistant", frame)

            if (cv2.waitKey(1) & 0xFF) == ord("q"):
                print("User pressed Q.")
                break
    except Exception as e:
        import traceback
        print("CRASH IN MAIN LOOP:")
        traceback.print_exc()
    finally:
        stop_speech()
        cap.release()
        cv2.destroyAllWindows()
        print("Assistant stopped.")


if __name__ == "__main__":
    main()