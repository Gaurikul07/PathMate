"""
PathMate — Personal AI Assistant  (Streaming Edition)
=====================================================
Seamlessly answers visual and general knowledge questions using Gemini.

KEY ARCHITECTURE (why this feels fast):
  1. Gemini responses are STREAMED token-by-token.
  2. Tokens are buffered into sentences.
  3. Each sentence is spoken via TTS THE MOMENT it's complete,
     while the next sentence is still being generated by Gemini.
  4. Result: user hears the first sentence in ~1-2s, not 5-10s.

FIXES APPLIED:
  - Gemini 3.5 Flash now defaults to "medium" thinking effort (it is NOT a
    pure non-thinking model). That reasoning delay happens before the first
    token streams out, which was the main source of the slowness. We now
    explicitly request thinking_level="low" to prioritize latency. If you
    need it even snappier for simple queries, try "minimal" instead.
  - Google's gemini-3.5-flash alias has a known intermittent 404 issue
    (routes to a decommissioned backing build) that is unrelated to your
    code. We now retry once automatically before giving up, instead of
    silently failing on the first hiccup.
  - The mic loop used to open/close a brand-new Microphone stream every
    ~150ms polling cycle, which adds latency and can clip the start of your
    wake word. It now uses listen_in_background so the audio stream stays
    open continuously and phrases are captured with no gaps.
  - Removed the hardcoded API key fallback. The script now loads
    GEMINI_API_KEY from a local .env file (or the environment) instead —
    never commit a real key into source code. See the setup note below.
  - The readiness message reads WAKE_WORD directly instead of a separate
    hardcoded string, so the two can never drift apart again.
  - TTS went silent after the very first utterance (the welcome message
    would play, but nothing after it). Root cause: pyttsx3's engine can
    only reliably run its say()/runAndWait() loop ONCE per instance —
    reusing the same engine for a second utterance silently produces no
    audio, no exception, nothing. This is a well-documented pyttsx3 quirk
    (most visible on Windows/SAPI5, but reported on other backends too),
    and it doesn't matter which thread the engine lives on — an earlier
    attempt at this fix moved engine creation into the worker thread,
    which addressed a real but different issue and didn't touch this one.
    The actual fix: create a brand-new pyttsx3 engine for every single
    utterance instead of reusing one long-lived engine.

SETUP — API KEY:
    1. pip install python-dotenv
    2. Create a file named ".env" next to this script containing:
           GEMINI_API_KEY=your_key_here
    3. Add ".env" to your .gitignore so it never gets committed.

Controls:
    Q  →  Quit (in the camera window)
    Say "Assistant, [your question]" to trigger the AI.
"""

import cv2
import os
import threading
import queue
import time
import platform
import subprocess
import re
from PIL import Image
import speech_recognition as sr
from google import genai
from google.genai import types

try:
    from dotenv import load_dotenv
    load_dotenv()  # reads GEMINI_API_KEY from a local .env file, if present
except ImportError:
    pass  # dotenv not installed — will still work if the env var is set another way

# ─────────────────────────────────────────────
# CONFIGURATION
# ─────────────────────────────────────────────
CAMERA_INDEX = 0
WAKE_WORD = "disha"
_OS = platform.system()

# API key comes from a local .env file or the environment — never hardcode
# a real key in source code (it ends up in git history, logs, and anywhere
# this file gets shared or pasted).
API_KEY = os.environ.get("GEMINI_API_KEY")
if not API_KEY:
    raise SystemExit(
        "Missing GEMINI_API_KEY.\n"
        "Either create a .env file next to this script with:\n"
        "  GEMINI_API_KEY=your_key_here\n"
        "or set it as an environment variable, e.g.:\n"
        "  export GEMINI_API_KEY=your_key_here      (macOS/Linux)\n"
        "  setx GEMINI_API_KEY your_key_here         (Windows)"
    )

# Gemini model — gemini-3.5-flash for low-latency streaming.
# NOTE: this model thinks by default (medium effort). We override that
# per-request below via thinking_level="low" to keep latency down.
MODEL = "gemini-3.5-flash"

# How many times to silently retry a request that fails before any text
# has streamed back (covers transient 404/429/503 errors from the API).
MAX_RETRIES = 2


# ─────────────────────────────────────────────
# STREAMING TTS ENGINE
#   • Dedicated worker thread pulls sentences off a queue and speaks
#     them one by one.
#   • flush_speech() lets us cancel pending speech instantly.
#
#   IMPORTANT: on Windows/Linux we create a FRESH pyttsx3 engine for
#   every utterance. Reusing a single long-lived engine across multiple
#   say()/runAndWait() calls is a well-known pyttsx3 issue — only the
#   first utterance ever gets spoken, and every call after that
#   silently produces no audio at all (no exception, nothing). Creating
#   a new engine per utterance costs a small amount of overhead but is
#   the reliable fix.
# ─────────────────────────────────────────────
_speech_queue: queue.Queue = queue.Queue()
_speech_stop = threading.Event()
_is_speaking = threading.Event()       # set while TTS is actively talking


def _speak_blocking(text: str):
    """Platform-aware blocking TTS call."""
    if _OS == "Darwin":
        try:
            subprocess.run(["say", "-r", "190", text], check=True)
        except Exception as e:
            print(f"[TTS Error] {e}")
        return

    if _OS in ("Windows", "Linux"):
        try:
            import pyttsx3
            engine = pyttsx3.init()   # fresh engine every time — see note above
            engine.setProperty("rate", 190)
            engine.say(text)
            engine.runAndWait()
            engine.stop()
            return
        except Exception as e:
            print(f"[TTS] pyttsx3 failed, falling back: {e}")

    if _OS == "Linux":
        try:
            subprocess.run(["espeak", "-s", "190", text], check=True)
        except Exception as e:
            print(f"[TTS Error] {e}")


def _speech_worker():
    while not _speech_stop.is_set():
        try:
            text = _speech_queue.get(timeout=0.3)
            if text is None:
                break
            _is_speaking.set()
            _speak_blocking(text)
            _is_speaking.clear()
            _speech_queue.task_done()
        except queue.Empty:
            continue
        except Exception:
            _is_speaking.clear()


# Start the speech worker immediately
threading.Thread(target=_speech_worker, daemon=True).start()


def speak(text: str):
    """Non-blocking — drops the sentence onto the TTS queue."""
    if text and text.strip():
        _speech_queue.put(text.strip())


def flush_speech():
    """Drain any pending sentences so we can start fresh."""
    while not _speech_queue.empty():
        try:
            _speech_queue.get_nowait()
            _speech_queue.task_done()
        except queue.Empty:
            break


def stop_speech():
    _speech_stop.set()
    try:
        _speech_queue.put_nowait(None)
    except queue.Full:
        pass


